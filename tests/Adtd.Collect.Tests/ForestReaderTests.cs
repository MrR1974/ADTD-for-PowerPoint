using Adtd.Model;
using Adtd.Model.Samples;

namespace Adtd.Collect.Tests;

public class ForestReaderTests
{
    static async Task<(ForestSnapshot Snapshot, List<CollectEvent> Events, FakeFactory Factory)> Read(
        ForestSnapshot source, CollectOptions? options = null, string[]? unreachable = null, Action<List<LdapEntry>>? tamper = null)
    {
        var dit = Dit.From(source);
        tamper?.Invoke(dit);
        var factory = new FakeFactory(dit, unreachable ?? []);
        var events = new List<CollectEvent>();
        var reader = new ForestReader(factory, FakeResolver.For(source), new SyncProgress<CollectEvent>(events.Add));
        var snapshot = await reader.ReadAsync(source.ForestName, options);
        return (snapshot, events, factory);
    }

    /// <summary>The snapshot without the fields that describe the collection run rather than the forest.</summary>
    static string Comparable(ForestSnapshot s) => SnapshotJson.Serialize(s with
    {
        CollectedAt = default, CollectedFrom = "", CollectorVersion = "", Warnings = [],
    });

    [Theory]
    [InlineData("single")]
    [InlineData("contoso")]
    [InlineData("large")]
    public async Task Reads_back_every_sample_forest_exactly(string name)
    {
        var source = SampleForests.ByName(name);
        var (read, _, _) = await Read(source);
        Assert.Equal(Comparable(source), Comparable(read));
    }

    [Fact]
    public async Task Classifies_every_kind_of_trust()
    {
        var (read, _, _) = await Read(SampleForests.Contoso());
        Trust T(string domain, string partner) => read.Domains.Single(d => d.DnsName == domain).Trusts.Single(t => t.Partner == partner);
        Assert.Equal(TrustKind.ParentChild, T("emea.contoso.com", "contoso.com").Kind);
        Assert.Equal(TrustKind.ParentChild, T("contoso.com", "apac.contoso.com").Kind);
        Assert.Equal(TrustKind.TreeRoot, T("contoso.com", "fabrikam.com").Kind);
        Assert.Equal(TrustKind.TreeRoot, T("fabrikam.com", "contoso.com").Kind);
        Assert.Equal(TrustKind.Shortcut, T("emea.contoso.com", "apac.contoso.com").Kind);
        Assert.Equal(TrustKind.Forest, T("contoso.com", "tailspin.example").Kind);
        Assert.Equal(TrustKind.External, T("emea.contoso.com", "partner.example").Kind);
        Assert.Equal(TrustDirection.Outbound, T("emea.contoso.com", "partner.example").Direction);
        Assert.Equal(TrustKind.Realm, T("fabrikam.com", "UNIX.EXAMPLE.COM").Kind);
    }

    [Fact]
    public async Task Reads_roles_flags_schedules_and_subnets()
    {
        var (read, _, _) = await Read(SampleForests.Contoso());
        var dc = read.DomainControllers.ToDictionary(d => d.Name);
        Assert.True(dc["BNE-AP04"].IsReadOnly);
        Assert.True(dc["BNE-AP04"].IsGlobalCatalog);
        Assert.False(dc["SYD-AP02"].IsGlobalCatalog);
        Assert.Equal("apac.contoso.com", dc["SYD-AP02"].Domain);
        Assert.Equal("Sydney", dc["SYD-AP02"].Site);
        Assert.Equal("Windows Server 2025 Datacenter", dc["TYO-AP07"].OperatingSystem);
        Assert.Equal(["10.0.0.19", "10.0.8.19"], dc["SYD-DC09"].IPv4);

        var root = read.Domains.Single(d => d.DnsName == "contoso.com");
        Assert.Equal(dc["SYD-DC01"].Key, root.PdcMaster);
        Assert.Equal(dc["SYD-DC02"].Key, root.RidMaster);
        Assert.Equal(dc["SYD-DC01"].Key, read.SchemaMaster);
        Assert.Null(root.ParentDns);
        Assert.Equal("contoso.com", read.Domains.Single(d => d.DnsName == "emea.contoso.com").ParentDns);

        Assert.Equal(120, read.SiteLinks.Single(l => l.Name == "London-Johannesburg").ScheduleHours);
        Assert.Null(read.SiteLinks.Single(l => l.Name == "Core").ScheduleHours);
        Assert.True(read.SiteLinks.Single(l => l.Name == "Core").ChangeNotification);
        Assert.Equal(4, read.SiteLinks.Single(l => l.Name == "Core").Sites.Count);
        Assert.True(read.Sites.Single(s => s.Name == "Dublin").UniversalGroupCaching);
        Assert.Null(read.Sites.Single(s => s.Name == "Madrid").Istg);

        Assert.Contains(read.Subnets, s => s.Prefix == "192.168.250.0/24" && s.Site == null);
        Assert.Contains(read.Connections, c => c.Name == "Disabled FRA-PAR" && !c.Enabled && !c.AutoGenerated);
        Assert.All(read.Connections.Where(c => c.Transport == "IP"),
            c => Assert.NotEqual(read.DomainControllers.Single(d => d.Key == c.From).Site, read.DomainControllers.Single(d => d.Key == c.To).Site));
    }

    [Fact]
    public async Task Warns_about_missing_addresses_and_unassigned_subnets()
    {
        var (read, events, _) = await Read(SampleForests.Contoso());
        Assert.Contains(read.Warnings, w => w.Contains("No IPv4 address found for sea-dc07.contoso.com"));
        Assert.Contains(read.Warnings, w => w.Contains("Subnet 192.168.250.0/24 isn't associated with a site"));
        Assert.Equal(read.Warnings.Count, events.Count(e => e.Level == CollectLevel.Warning));
    }

    [Fact]
    public async Task Skips_address_lookup_when_asked()
    {
        var (read, _, _) = await Read(SampleForests.Single(), new CollectOptions { ResolveAddresses = false });
        Assert.All(read.DomainControllers, d => Assert.Empty(d.IPv4));
        Assert.DoesNotContain(read.Warnings, w => w.Contains("IPv4"));
    }

    [Fact]
    public async Task Carries_on_when_a_domain_is_unreachable()
    {
        var (read, _, factory) = await Read(SampleForests.Contoso(), unreachable: ["fabrikam.com"]);
        var fab = read.Domains.Single(d => d.DnsName == "fabrikam.com");
        Assert.False(fab.Reachable);
        Assert.Null(fab.PdcMaster);
        Assert.Empty(fab.Trusts);
        Assert.True(read.Domains.Where(d => d.DnsName != "fabrikam.com").All(d => d.Reachable && d.PdcMaster != null));
        // its DCs are still there, with operating systems read from a global catalog
        Assert.All(read.DomainControllers.Where(d => d.Domain == "fabrikam.com"), d => Assert.NotNull(d.OperatingSystem));
        Assert.Contains("contoso.com:3268", factory.Connected);
        Assert.Contains(read.Warnings, w => w.StartsWith("Domain fabrikam.com couldn't be reached"));
    }

    [Fact]
    public async Task Fails_clearly_when_the_target_is_unreachable()
    {
        var ex = await Assert.ThrowsAsync<DirectoryUnavailableException>(() => Read(SampleForests.Single(), unreachable: ["corp.example"]));
        Assert.Contains("corp.example", ex.Message);
    }

    [Fact]
    public async Task Leaves_out_connections_from_deleted_DCs_and_flags_deleted_role_holders()
    {
        var source = SampleForests.Single();
        var config = "CN=Configuration,DC=corp,DC=example";
        var deleted = $"CN=NTDS Settings\\0ADEL:1234,CN=OLD-DC,CN=Servers,CN=Head-Office,CN=Sites,{config}";
        var (read, _, _) = await Read(source, tamper: dit =>
        {
            var to = source.DomainControllers[0].Key;
            dit.Add(new LdapEntry($"CN=ghost,{to}", new Dictionary<string, string[]>(StringComparer.OrdinalIgnoreCase)
            {
                ["objectClass"] = ["nTDSConnection"], ["name"] = ["ghost"], ["fromServer"] = [deleted],
            }));
            var i = dit.FindIndex(e => e.Dn == "CN=Infrastructure,DC=corp,DC=example");
            dit[i] = new LdapEntry(dit[i].Dn, new Dictionary<string, string[]>(StringComparer.OrdinalIgnoreCase) { ["fSMORoleOwner"] = [deleted] });
        });
        Assert.DoesNotContain(read.Connections, c => c.Name == "ghost");
        Assert.Contains(read.Warnings, w => w.Contains("replicates from a deleted DC"));
        Assert.Contains(read.Warnings, w => w.Contains("held by a deleted DC (OLD-DC)"));
    }

    [Fact]
    public async Task Logs_every_query_for_remote_diagnosis()
    {
        var (_, events, _) = await Read(SampleForests.Single());
        var details = events.Where(e => e.Level == CollectLevel.Detail).Select(e => e.Message).ToList();
        Assert.Contains(details, m => m.Contains("(objectClass=nTDSDSA)") && m.Contains("→ 3"));
        Assert.Contains(details, m => m.Contains("(objectClass=subnet)") && m.Contains("→ 3"));
        Assert.Contains(events, e => e.Level == CollectLevel.Step && e.Message.StartsWith("Found 1 domain(s), 2 site(s), 3 domain controller(s)"));
    }

    /// <summary>Progress&lt;T&gt; posts to the thread pool; tests need events in order and complete on return.</summary>
    sealed class SyncProgress<T>(Action<T> report) : IProgress<T>
    {
        public void Report(T value) => report(value);
    }
}

public class DnTests
{
    [Fact]
    public void Splits_on_unescaped_commas_only()
    {
        Assert.Equal(["CN=Smith\\, John", "OU=People", "DC=corp"], Dn.Split("CN=Smith\\, John,OU=People,DC=corp"));
        Assert.Equal("Smith, John", Dn.Value("CN=Smith\\, John,OU=People,DC=corp"));
        Assert.Equal("OU=People,DC=corp", Dn.Parent("CN=Smith\\, John,OU=People,DC=corp"));
    }

    [Fact]
    public void Reads_DNS_names_and_deleted_markers()
    {
        Assert.Equal("emea.contoso.com", Dn.ToDns("CN=x,DC=emea,DC=contoso,DC=com"));
        Assert.True(Dn.IsDeleted("CN=NTDS Settings\\0ADEL:6a1b,CN=DC1,CN=Servers"));
        Assert.False(Dn.IsDeleted("CN=NTDS Settings,CN=DC1,CN=Servers"));
        Assert.Equal("DC1", Dn.ValueAt("CN=NTDS Settings,CN=DC1,CN=Servers", 1));
    }

    [Theory]
    [InlineData(0)]
    [InlineData(120)]
    [InlineData(168)]
    public void Schedule_blobs_round_trip(int hours) => Assert.Equal(hours, ScheduleBlob.AvailableHours(ScheduleBlob.Encode(hours)));

    [Fact]
    public void Unreadable_schedules_are_null() => Assert.Null(ScheduleBlob.AvailableHours([1, 2, 3]));
}
